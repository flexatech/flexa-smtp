#!/usr/bin/env node
// Extract __() / _n() / _x() calls from .tsx/.ts sources into a JS shim that
// `wp i18n make-pot` can scan. WP-CLI's bundled i18n-command only parses
// .js/.jsx; this script bridges the gap for our React app.

import { promises as fs } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(process.argv[2] || "apps/admin/src");
const OUT = path.resolve(process.argv[3] || "i18n/.extracted-strings.js");

const SKIP_DIRS = new Set(["node_modules", ".git", "dist", "build"]);

async function walk(dir, files = []) {
    let entries;
    try {
        entries = await fs.readdir(dir, { withFileTypes: true });
    } catch {
        return files;
    }
    for (const e of entries) {
        if (e.name.startsWith(".")) continue;
        if (SKIP_DIRS.has(e.name)) continue;
        const p = path.join(dir, e.name);
        if (e.isDirectory()) {
            await walk(p, files);
        } else if (/\.(tsx?|jsx?)$/.test(e.name)) {
            files.push(p);
        }
    }
    return files;
}

// Walk `src` from `start` until we balance the outer `(` we just saw, returning
// raw comma-separated argument slices. Handles nested parens and string
// literals. We do not strip comments; they almost never appear inside __()
// argument lists in this codebase.
function parseArgList(src, start) {
    let depth = 0;
    let i = start;
    let argStart = i;
    const args = [];
    while (i < src.length) {
        const c = src[i];
        if (c === '"' || c === "'" || c === "`") {
            const q = c;
            i++;
            while (i < src.length && src[i] !== q) {
                if (src[i] === "\\") i++;
                i++;
            }
            i++;
            continue;
        }
        if (c === "(") depth++;
        else if (c === ")") {
            if (depth === 0) {
                args.push(src.slice(argStart, i).trim());
                return { end: i + 1, args };
            }
            depth--;
        } else if (c === "," && depth === 0) {
            args.push(src.slice(argStart, i).trim());
            argStart = i + 1;
        }
        i++;
    }
    return null;
}

const CALL_RE = /(?<![\w$.])(_{1,2}|_x|_n)\s*\(/g;

function isStringLit(s) {
    if (s.length < 2) return false;
    const first = s[0];
    const last = s[s.length - 1];
    if (first !== last) return false;
    return first === '"' || first === "'" || first === "`";
}

const out = [];
const files = await walk(ROOT);
for (const file of files) {
    const src = await fs.readFile(file, "utf8");
    let m;
    while ((m = CALL_RE.exec(src))) {
        const fn = m[1];
        const parsed = parseArgList(src, CALL_RE.lastIndex);
        if (!parsed) continue;
        CALL_RE.lastIndex = parsed.end;
        const args = parsed.args;
        // WP-CLI's JsCodeExtractor requires the textdomain literal as the
        // last argument — otherwise the call is silently dropped. We always
        // append our domain so every extracted string lands in the POT.
        const DOMAIN = '"flexa-smtp"';
        if (fn === "__") {
            if (args.length >= 1 && isStringLit(args[0])) {
                out.push(`__(${args[0]}, ${DOMAIN});`);
            }
        } else if (fn === "_x") {
            if (
                args.length >= 2 &&
                isStringLit(args[0]) &&
                isStringLit(args[1])
            ) {
                out.push(`_x(${args[0]}, ${args[1]}, ${DOMAIN});`);
            }
        } else if (fn === "_n") {
            if (
                args.length >= 3 &&
                isStringLit(args[0]) &&
                isStringLit(args[1])
            ) {
                out.push(`_n(${args[0]}, ${args[1]}, 1, ${DOMAIN});`);
            }
        }
    }
}

await fs.mkdir(path.dirname(OUT), { recursive: true });
await fs.writeFile(
    OUT,
    "// AUTO-GENERATED by scripts/extract-tsx-i18n.mjs. Do not edit.\n" +
        out.join("\n") +
        "\n",
    "utf8",
);
console.log(`Extracted ${out.length} calls from ${files.length} files → ${OUT}`);
